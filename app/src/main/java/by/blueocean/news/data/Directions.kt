    fun match(articleText: String): List<Direction> {
        val text = articleText.lowercase()
        if (text.isBlank()) return emptyList()
        return ALL.filter { direction ->
            direction.keywords.count { text.contains(it) } >= 2
        }
    }

    fun best(direction: Direction): String = direction.howToEarn
